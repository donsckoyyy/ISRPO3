// советы, которые показываются в напоминании
const TIPS = [
	'Пора завязывать, все деньги мира не заработаешь',
	'Выйди из за компа!',
	'Семья уже ищет тебя по всему городу, напомни ей о своем существовании',
	'Если не хочешь ощутить геморрой, оставь комп в покое',
	'Пройдись по комнате, разомни ноги, пока не засох',
];

// Возвращает случайный совет из списка
export function randomTip(): string {
	return TIPS[Math.floor(Math.random() * TIPS.length)];
}
