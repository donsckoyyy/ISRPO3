const TIPS = [
	'Встань и разомни шею: медленные наклоны головы влево-вправо.',
	'Выпей стакан воды 💧',
	'Гимнастика для глаз: посмотри вдаль на 20 секунд.',
	'Покрути плечами вперёд и назад по 10 раз.',
	'Пройдись по комнате, разомни ноги.',
	'Закрой глаза и сделай 5 глубоких вдохов.',
	'Потянись вверх, сцепив руки в замок.',
];

// Возвращает случайный совет из списка
export function randomTip(): string {
	return TIPS[Math.floor(Math.random() * TIPS.length)];
}
